from playwright.sync_api import sync_playwright
with sync_playwright() as p:
 b=p.chromium.launch()
 page=b.new_page()
 page.route('**/api/**',lambda r:r.fulfill(json={'authenticated':False,'registrationEnabled':True,'demoEnabled':True}))
 page.goto('http://127.0.0.1:8877/static/index.html')
 page.wait_for_timeout(500)
 page.keyboard.press('Control+k')
 assert page.locator('#tastePalette').evaluate("e=>e.classList.contains('hidden')")
 page.evaluate("document.querySelector('#authScreen').classList.add('hidden');document.querySelector('#appShell').classList.remove('hidden')")
 page.locator('#tasteSearch').click()
 page.wait_for_timeout(150)
 assert page.locator('body').evaluate("e=>e.classList.contains('ui-scroll-lock')")
 page.locator('#tastePaletteInput').fill('任务')
 assert '执行' in page.locator('#tastePaletteResults').inner_text()
 page.keyboard.press('Shift+Tab')
 assert page.locator('#tastePalette').evaluate('e=>e.contains(document.activeElement)')
 page.keyboard.press('Escape')
 page.wait_for_timeout(150)
 assert page.locator('#tastePalette').evaluate("e=>e.classList.contains('hidden')")
 assert not page.locator('body').evaluate("e=>e.classList.contains('ui-scroll-lock')")
 page.set_viewport_size({'width':390,'height':844})
 page.evaluate("document.querySelector('#authScreen').classList.remove('hidden');document.querySelector('#appShell').classList.add('hidden')")
 assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
 page.emulate_media(reduced_motion='reduce')
 assert page.locator('#authSubmit').evaluate("e=>parseFloat(getComputedStyle(e).transitionDuration)<.01")
 b.close()
print('PASS: login shortcut guard, search, focus trap, Escape, scroll unlock, mobile width, reduced motion')
